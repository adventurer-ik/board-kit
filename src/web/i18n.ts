export const DICTS: Record<string, Dict> = { ko, en };

/** `{name}` 자리를 채우는 번역 함수 */
export function makeT(lang: string, overrides?: Partial<Dict>): (key: DictKey, vars?: Record<string, string | number>) => string {
  const d = { ...(DICTS[lang] ?? en), ...(overrides ?? {}) };
  return (key, vars) => {
    let s = d[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
